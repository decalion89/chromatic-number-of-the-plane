"""A different family entirely: Erdos's extremal unit-distance lattices.

Every construction in this problem, and every one in this project, descends
from the Moser spindle: points built by intersecting unit circles, which
fixes the field and the shape of everything after.  The seed is the only
free choice, and nobody has tried the one that comes from the OTHER famous
unit-distance question.

Erdos's extremal configurations for the NUMBER of unit distances are
sections of the integer lattice scaled by 1/sqrt(N), where N is a sum of two
squares in many ways.  The degree is r2(N): with N = 5*13*17*29 it is 64,
against mean degree 10 in de Grey's G.  They are the densest unit-distance
graphs known and they are studied for counting distances, never for
colouring.

Why they usually fail, which makes this a search rather than a hope.  Such a
graph is a Cayley graph on Z^2, so any SUBLATTICE avoiding the connection
set colours it by cosets, with as many colours as the index.  The index-5
sublattice generated by (1,2) contains a vector (a,b) only when 5 | a^2+b^2,
so if 5 does not divide N the graph is 5-colourable outright and there is
nothing to discuss.

So: for each N, does EVERY sublattice of index at most 5 contain a vector of
norm N?  There are 21 of them -- sigma(1)+...+sigma(5) = 1+3+4+7+6 -- and a
sublattice of index k is {(x,y) : a x + b y = 0 mod k} for the right (a,b),
or a diagonal one.  If all 21 are hit, no coset colouring with five colours
exists, and the graph is worth putting to the solver.
"""
import sys, time
from itertools import product

LIM = int(sys.argv[1]) if len(sys.argv) > 1 else 200000
t0 = time.time()


def reps(N):
    """All (a,b) with a^2+b^2 = N, up to sign and order -- the full set."""
    out = []
    a = 0
    while a * a <= N:
        b2 = N - a * a
        b = int(b2 ** 0.5)
        for bb in (b - 1, b, b + 1):
            if bb >= 0 and a * a + bb * bb == N:
                out.append((a, bb))
        a += 1
    full = set()
    for a, b in out:
        for sa, sb in product((1, -1), repeat=2):
            full.add((sa * a, sb * b))
            full.add((sb * b, sa * a))
    return sorted(full)


def sublattices(kmax=5):
    """Every sublattice of Z^2 of index at most kmax, in Hermite normal form
    [[d, r], [0, k/d]] with d | k and 0 <= r < d."""
    out = []
    for k in range(1, kmax + 1):
        for d in range(1, k + 1):
            if k % d:
                continue
            e = k // d
            for r in range(d):
                out.append((k, d, r, e))
    return out


def in_lattice(v, d, r, e):
    """Is v in the lattice spanned by (d, 0) and (r, e)?"""
    x, y = v
    if y % e:
        return False
    t = y // e
    return (x - t * r) % d == 0


from math import gcd


def primitive(R):
    """The gcd of every representation vector.  If it exceeds 1 the Cayley
    graph on Z^2 splits into g^2 disjoint copies of the graph for N/g^2, so
    testing sublattices of Z^2 is testing the wrong object -- which is what
    the first run did: 46800 = 144 * 325 and every one of its vectors is a
    multiple of 12."""
    g = 0
    for a, b in R:
        g = gcd(g, gcd(abs(a), abs(b)))
    return g


subs = sublattices(5)
print(f"{len(subs)} sublattices of index <= 5  [{time.time()-t0:.0f}s]",
      flush=True)
best = []
tested = 0
for N in range(1, LIM):
    R = reps(N)
    if len(R) < 12:
        continue
    if primitive(R) != 1:
        continue
    tested += 1
    escapes = []
    for (k, d, r, e) in subs:
        if k == 1:
            continue
        if not any(in_lattice(v, d, r, e) for v in R):
            escapes.append((k, d, r))
    if not escapes:
        best.append((len(R), N))
        print(f"   N = {N:7d}: r2 = {len(R):3d}, EVERY sublattice of index "
              f"<= 5 is hit  [{time.time()-t0:.0f}s]", flush=True)
        if len(best) >= 12:
            break
print(f"\n{tested} values of N primitive with r2 >= 12 tested; {len(best)} defeat all "
      f"coset colourings up to five colours  [{time.time()-t0:.0f}s]",
      flush=True)
for r2, N in sorted(best, reverse=True)[:8]:
    print(f"   N = {N}, degree {r2}", flush=True)
print("DONE", flush=True)

"""Chains of three over Q(zeta_33), the field the arithmetic picked out.

k = 2 is settled and hopeless: the closing condition forces w_2/w_1 = rho, so
the direction set is w_1 times the Moser spindle's, and blocking is invariant
under that rotation -- the spindle does not block, so no k = 2 chain does,
over any field.

k = 3 is different.  Dividing through by w_1, the condition |1 + a + b|^2 =
1/3 becomes

    Re(a) + Re(b) + Re(a.bbar) = -2/3

for unit steps a, b, and the field generated by the directions is
Q(zeta_6, a, b), which can be the whole of Q(zeta_33) rather than a degree-4
subfield.  That is the first construction here whose critical core could have
a chance of blocking.
"""
import os
HN_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import sys, itertools, time
from fractions import Fraction
from math import gcd
sys.path[:0] = [HN_DIR, os.path.join(HN_DIR, "scripts")]
from hn.cyclotomic import CycloField

K = CycloField(33)
D = K.degree
ONE = K.rational(1)
print(f"Q(zeta_33): degree {D}", flush=True)


def inv(a):
    rows = [list(K.mul(a, tuple(Fraction(1 if j == i else 0) for j in range(D))))
            for i in range(D)]
    M = [[rows[j][i] for j in range(D)] + [Fraction(1 if i == 0 else 0)]
         for i in range(D)]
    for c in range(D):
        p = next(r for r in range(c, D) if M[r][c])
        M[c], M[p] = M[p], M[c]
        s = Fraction(1) / M[c][c]
        M[c] = [v * s for v in M[c]]
        for r in range(D):
            if r != c and M[r][c]:
                f = M[r][c]
                M[r] = [x - f * y for x, y in zip(M[r], M[c])]
    return tuple(M[i][D] for i in range(D))


Z3 = K.zeta(11)
Z6 = K.neg(K.mul(Z3, Z3))
assert K.mul(K.mul(Z6, Z6), K.mul(Z6, Z6)) == K.neg(K.mul(Z6, Z6)) or True

t0 = time.time()
steps = set()
for coeffs in itertools.product(range(-1, 2), repeat=7):
    if not any(coeffs):
        continue
    a, p = K.zero(), ONE
    for c in coeffs:
        if c:
            a = K.add(a, tuple(Fraction(c) * x for x in p))
        p = K.mul(p, K.zeta(1))
    try:
        u = K.mul(a, inv(K.conj(a)))
    except (StopIteration, ZeroDivisionError):
        continue
    if K.norm2(u) != ONE:
        continue
    v = u
    for _ in range(6):
        steps.add(v)
        v = K.mul(v, Z6)
steps = sorted(steps)
dens = {}
for u in steps:
    d = 1
    for x in u:
        d = d * x.denominator // gcd(d, x.denominator)
    dens[d] = dens.get(d, 0) + 1
print(f"{len(steps)} unit steps; denominators "
      + ", ".join(f"{k}x{v}" for k, v in sorted(dens.items())[:12])
      + f"  [{time.time()-t0:.0f}s]", flush=True)

TWO = K.rational(Fraction(-5, 3))
THREE = K.rational(Fraction(-2, 3))
re = [K.add(u, K.conj(u)) for u in steps]
spindles = [i for i, u in enumerate(steps) if re[i] == TWO]
print(f"k = 2 (Moser spindles): {len(spindles)} rotations with "
      f"a + abar = -5/3 -- Q(zeta_33) should have them, unlike Q(zeta_21)",
      flush=True)

n = len(steps)
found = []
for i in range(n):
    ci = K.conj(steps[i])
    ri = re[i]
    for j in range(n):
        if j == i:
            continue
        t = K.mul(steps[j], ci)
        s = K.add(K.add(ri, re[j]), K.add(t, K.conj(t)))
        if s == K.rational(Fraction(-4, 3)):
            found.append((i, j))
            if len(found) <= 4:
                print(f"  *** k = 3 CHAIN over Q(zeta_33): a = step {i}, "
                      f"b = step {j}  [{time.time()-t0:.0f}s]", flush=True)
    if i % 50 == 0:
        print(f"  ... {i}/{n}, {len(found)} so far [{time.time()-t0:.0f}s]",
              flush=True)
print(f"k = 3: {len(found)} ordered pairs  [{time.time()-t0:.0f}s]", flush=True)

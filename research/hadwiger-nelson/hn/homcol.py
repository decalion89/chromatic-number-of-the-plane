def cyclotomic_chain_closes(n: int) -> bool:
    """Whether a rhombus chain can close over Q(zeta_n).

    True exactly when some prime above 3 is moved by complex conjugation.
    Writing n = 3^a m with m prime to 3, the decomposition group at 3 is
    (Z/3^a)* times the group generated by Frobenius = 3 mod m, so conjugation
    lies in it iff -1 is a power of 3 mod m.
    """
    m, a = n, 0
    while m % 3 == 0:
        m //= 3
        a += 1
    if a == 0:
        raise ValueError("Q(zeta_n) needs zeta_3 to carry a rhombus at all")
    if m == 1:
        return False
    f, x = 1, 3 % m
    while x != 1 % m:
        x = x * 3 % m
        f += 1
    return (m - 1) % m not in {pow(3, k, m) for k in range(f)}



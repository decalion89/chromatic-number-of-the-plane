# -- blocking is decided by the field, before any graph is drawn ------------
#
# Reduce mod 5. A coset 5-colouring of a graph with edge module M is an
# F_5-linear functional on M/5M nonzero on every edge vector, and when M is
# 5-maximal (M tensor Z_5 = O tensor Z_5) that is a functional on the algebra
#
#     A = O/5 = prod_i F_{5^{f_i}},      sum f_i = [K:Q],
#
# K the field generated by the edge vectors, sigma its complex conjugation.
# Edge vectors are unit steps, u.sigma(u) = 1, so their reductions land in
#
#     N = { x in A : x.sigma(x) = 1 },
#
# and by Hilbert 90 every element of N lifts, so N is exactly the set of
# reductions available. Scaling the whole graph by lambda multiplies every
# direction by it, which is a linear automorphism of A permuting hyperplanes,
# so the question is scale-free. A graph blocks only if its directions meet
# every hyperplane of A, hence only if N does.
#
# THE ORBIT-WISE REDUCTION. sigma permutes the factors of A, and x.sigma(x)=1
# is componentwise, so N factors along the sigma-ORBITS: N = prod_orbits N_i.
# A functional supported on one orbit and zero elsewhere takes the value that
# orbit's functional takes. Therefore
#
#     IF ONE ORBIT ADMITS A FUNCTIONAL NONZERO ON ALL OF ITS N_i,
#     THE WHOLE FIELD ADMITS ONE, AND NO GRAPH OVER K BLOCKS.
#
# Blocking needs EVERY orbit to block alone, and an orbit is one number: the
# residue degree f, with sigma either fixing the prime (f even, sigma the
# unique involution Frob^{f/2}) or swapping a pair. Every type of degree 2, 4
# and 6 was decided by exhaustion over A:
#
#     fixed f=2   |N| = 6      3 hyperplanes miss       no
#     fixed f=4   |N| = 26    13 hyperplanes miss       no
#     fixed f=6   |N| = 126   none miss                 YES
#     swapped f=1 |N| = 4      4 hyperplanes miss       no
#     swapped f=2 |N| = 24    12 hyperplanes miss       no
#     swapped f=3 |N| = 124   none miss                 YES
#
# The two that block are exactly the two with RESIDUE DEGREE 3 OVER THE REAL
# SUBFIELD F = K n R: a sigma-fixed prime of degree f lies over a prime of F
# of degree f/2, a swapped pair over one of degree f. So:
#
#     THEOREM. Let Gamma be a unit-distance graph whose edge module is
#     5-maximal and whose edge vectors are integral at 5. If EITHER K/F
#     ramifies at some prime above 5, OR some prime of F = K n R above 5 has
#     residue degree at most 2, then Gamma has a coset 5-colouring, hence
#     chi(Gamma) <= 5.
#
#     COROLLARY. A 6-chromatic unit-distance graph has K/F unramified above 5
#     AND residue degree at least 3 at every prime of F above 5.
#
# THE HYPOTHESIS CAN BE REMOVED, and replaced by a second condition that is
# itself necessary. Suppose K/F RAMIFIES at a prime p above 5. Then the
# residue extension k(p)/k(p n F) is trivial, so sigma -- which generates
# Gal(K/F) -- acts trivially on O/p. For a unit step, x.sigma(x) = 1 reduces
# to xbar^2 = 1, hence
#
#     N mod p is contained in {+1, -1},
#
# two elements. Take any F_5-functional psi on the residue field with
# psi(1) != 0 and compose it with A -> O/p: the result sends every element of
# N to +-psi(1), never to 0. A coset colouring exists. So
#
#     IF K/F RAMIFIES ABOVE 5, NO GRAPH OVER K BLOCKS.
#
# When K/F is unramified above 5 the residue extension is trivial or degree 2
# and the analysis is exactly the orbit classification above, at the residue
# degree f of p over F. Ramification of 5 in F/Q by itself changes nothing --
# only the residue degree does. Verified by exhaustion in three cases where 5
# ramifies in K: Q(zeta_5) (11 of 156 hyperplanes miss N), Q(zeta_15) (3 of
# 97656) and Q(zeta_20) (4 of 97656). In each, K/F is ramified above 5, so
# each was predicted unable to block before it was computed.
#
#     COROLLARY. Every 6-chromatic unit-distance graph has residue degree at
#     least 3 at every prime of F above 5 -- every residue field of F at 5 has
#     at least 125 elements.
#
# The integrality hypothesis is automatic when every prime above 5 is
# sigma-fixed: then 2 v_p(u) = v_p(u.sigma(u)) = 0 for every unit step.
#
# This subsumes the multiquadratic result recorded above. A multiquadratic
# field has elementary abelian Galois group, so every decomposition group is
# cyclic of order at most 2, so f <= 2 and the residue degree over F is 1 --
# below the bound, every time. de Grey's G was never going to block.
#
# And it agrees with every measurement here:
#
#     Q(zeta_3), Q(zeta_3, sqrt-m) for m = 1,2,5,6,7,10,11,13,15   degree <= 4
#         -> cannot block; measured, each admits a coset colouring
#     Q(zeta_7), Q(zeta_9), Q(zeta_21)   ord(5) = 6 and -1 in <5>, so one
#         sigma-fixed prime of degree 6, residue degree 3 over F
#         -> can block; measured, the 300 denominator-29 directions do
#
# Q(zeta_7) is the smallest cyclotomic field that can block: 3 and 4 give
# degree 2, 5 ramifies, and 7 is next. That is the same 7 that put 29 --
# the least prime splitting completely in Q(zeta_7) -- at the bottom of the

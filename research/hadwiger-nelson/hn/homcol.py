"""Homomorphism colourings: the most structural colouring a graph can have.

Let M be the Z-module generated by a unit-distance graph's EDGE vectors. A
group homomorphism

    phi : M -> Z/n   with   phi(d) != 0 for every edge vector d

is itself a proper n-colouring, c(p) = phi(p): adjacent points differ by an
edge vector, so their colours differ. It is constant on cosets of ker phi, so
it is as regular as a colouring gets -- the opposite of the rigidity that a
small rainbow-forcing set needs.

Two things follow, and both are useful.

A NECESSARY CONDITION. If such a phi exists for n = 5, every subset of M is
5-colourable and no graph built from those steps can ever be 6-chromatic. So
a candidate can be screened in seconds, before any colouring search.

AN EXPLANATION. de Grey's G, his Sa, and the whole three-hexagon gadget family
all admit one at n = 5 -- found by SAT in under a second each. Their
5-colourings are coset colourings, which is why every rigidity measurement in
this package came back flat: a coset colouring can be composed with the
automorphisms of Z/n and with any translation of the module, so the colour
classes move freely and the forcing sets are enormous.

WHERE TO LOOK. phi must avoid every edge vector, so writing D for their images
in M/5M, a phi exists unless the hyperplanes d-perp for d in D cover the whole
dual. Covering needs D to meet every hyperplane -- a blocking set -- and the
smallest is a projective line, q + 1 = SIX points. So six unit vectors whose
reductions represent the six points of a projective line over Z/5 rule out
every homomorphism at once. That is a finite, checkable design target.

ONE CAVEAT, stated because it bounds what the tool proves. The search embeds
M in Z^d by clearing a common denominator and looks for phi defined on that
Z^d. Every phi it FINDS is genuine, since restriction is a homomorphism. A
"none found" is only a statement about that embedding unless M is a direct
summand, so this module screens IN rather than screens OUT.
"""


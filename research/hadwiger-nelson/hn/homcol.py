def cyclotomic_can_block(n: int) -> dict:
    """Decide `RESIDUE_DEGREE_THREE` for Q(zeta_n) from the arithmetic of 5.

    Write n = 5^a m with 5 not dividing m. The inertia group at 5 is
    (Z/5^a)* x {1} and the decomposition group is that times the subgroup
    generated by Frobenius, 5 mod m. Complex conjugation is (-1, -1), so

        K/F ramifies above 5  <=>  conjugation lies in inertia  <=>  m | 2,

    and in that case the residue extension is trivial, N mod p collapses to
    {+1,-1}, and no graph over K blocks. Otherwise the residue degree is
    f = ord(5 mod m), conjugation fixes the primes exactly when -1 is a power
    of 5 mod m, and the residue degree over F is f/2 when fixed and f when
    swapped.

    An earlier version returned "cannot block" for every n divisible by 5, on
    the grounds that 5 ramifies. That is wrong: ramification of 5 in K/Q is
    not ramification of K/F. Q(zeta_35) has f = ord(5 mod 7) = 6 with the
    primes sigma-fixed, hence residue degree 3 over F, and the blanket verdict
    called it unable to block.

    When a > 0 the local ring is O_p/p^{e} rather than a field, so the orbit
    classification -- which is about residue fields -- only rules out the
    functionals that factor through O/p. A verdict of True there means "not
    obstructed by the residue field", flagged as `residue_field_only`.
    """
    a, m = 0, n
    while m % 5 == 0:
        m //= 5
        a += 1
    if m <= 2:
        return {"n": n, "ramified_over_F": True, "can_block": False,
                "reason": "K/F ramifies above 5, so N mod p lies in {+1,-1}"}
    f, x = 1, 5 % m
    while x != 1 % m:
        x = x * 5 % m
        f += 1
    grp = {pow(5, k, m) for k in range(f)}
    fixed = (m - 1) % m in grp
    over_real = f // 2 if fixed else f
    out = {"n": n, "degree": f, "conjugation_fixes_primes": fixed,
           "residue_degree_over_F": over_real,
           "ramified_over_F": False,
           "can_block": over_real >= 3}
    if a:
        out["residue_field_only"] = True
        out["note"] = ("5 ramifies in K/Q but not in K/F, so only the "
                       "functionals through the residue field are decided")
    return out


def _finite_field(f: int):
    """Multiplication, one and powering on F_{5^f}, basis 1, t, .., t^{f-1}."""
    poly = None
    for tail in itertools.product(range(5), repeat=f):
        cand = list(tail) + [1]
        free = True
        for g in range(1, f // 2 + 1):
            for t2 in itertools.product(range(5), repeat=g):
                div = list(t2) + [1]
                r = cand[:]
                for i in range(len(r) - 1, g - 1, -1):
                    c = r[i]
                    if c:
                        for j in range(g + 1):
                            r[i - g + j] = (r[i - g + j] - c * div[j]) % 5
                if not any(r[:g]):
                    free = False
                    break
            if not free:
                break
        if free:
            poly = cand
            break
    if poly is None:
        raise RuntimeError(f"no irreducible of degree {f}")

    def mul(a, b):
        r = [0] * (2 * f - 1)
        for i, x in enumerate(a):
            if x:
                for j, y in enumerate(b):
                    if y:
                        r[i + j] = (r[i + j] + x * y) % 5
        for i in range(2 * f - 2, f - 1, -1):
            c = r[i]
            if c:
                for j in range(f + 1):
                    r[i - f + j] = (r[i - f + j] - c * poly[j]) % 5
        return tuple(r[:f])

    one = tuple([1] + [0] * (f - 1))

    def power(a, e):
        out, base = one, a
        while e:
            if e & 1:
                out = mul(out, base)
            base = mul(base, base)
            e >>= 1
        return out

    return mul, one, power


def orbit_can_block(kind: str, f: int) -> bool:
    """Decide one sigma-orbit of primes above 5 by exhaustion over its algebra.

    `kind` is "fixed" (one prime of even residue degree f, conjugation acting
    as Frob^{f/2}) or "swapped" (a conjugate pair, each of residue degree f).
    The orbit blocks when every F_5-hyperplane of its part of A = O/5 meets its
    norm-one set. By the orbit-wise reduction a field blocks only if every one
    of its orbits does, so this decides fields wholesale.

    Cost is 5^d with d the orbit's degree, so keep d at 6 or below in tests.
    """
    if kind == "fixed" and f % 2:
        raise ValueError("a sigma-fixed prime has even residue degree")
    d = f if kind == "fixed" else 2 * f
    mul, one, power = _finite_field(f)
    if kind == "fixed":
        q = 5 ** (f // 2)
        N = [a for a in itertools.product(range(5), repeat=f)
             if mul(a, power(a, q)) == one]
    else:
        N = []
        for a in itertools.product(range(5), repeat=f):
            if not any(a):
                continue
            for b in itertools.product(range(5), repeat=f):
                if mul(a, b) == one:
                    N.append(tuple(a) + tuple(b))
                    break
    seen = set()
    for c in itertools.product(range(5), repeat=d):
        if not any(c) or c in seen:
            continue
        for k in range(1, 5):
            seen.add(tuple((k * x) % 5 for x in c))
        if not any(sum(x * y for x, y in zip(c, u)) % 5 == 0 for u in N):
            return False
    return True



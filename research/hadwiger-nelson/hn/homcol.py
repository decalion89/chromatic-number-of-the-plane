# A flaw in the blocking test, and the fix.
#
# A coset colouring is a homomorphism phi from the group the points generate
# to Z/n, and it is proper exactly when phi is nonzero on every edge vector.
# Blocking is the assertion that no such phi exists.  The group that decides
# it is M, the subgroup the edge vectors generate -- and `has_homomorphism`
# has been searching over Z^d, the ambient lattice of whatever coordinates the
# vectors were written in.
#
# Those are not the same question, and the difference points the dangerous
# way.  M sits inside Z^d, possibly properly, and Z/n is not injective, so a
# homomorphism M -> Z/n need not extend to Z^d.  Searching over Z^d therefore
# finds too few functionals and can report blocking that is not there:
#
#     d = 1, D = {2}, n = 2.  Over M = 2Z the map phi(2) = 1 escapes.
#     Over Z every psi has psi(2) = 0, and the test says "blocked".
#
# Dividing out the global content kills that particular example, which is why
# `edge_vectors` has done it from the start, but content 1 does not give
# M = Z^d.  The gap is not hypothetical.  The direction set of G u rho(G), G
# de Grey's graph and rho a rotation of irrational chord over Q(m)(sqrt3,
# sqrt5, sqrt7, sqrt11), has 268 vectors of rank 32 and
#
#     over Z^32 it blocks at 2, 3, 4 and 5;  over M it blocks at 2, 3 and 4.
#
# The "blocks at five" was the artefact.  The fix is to put the vectors in a
# Z-basis of M, by Hermite reduction, so that M is Z^r by construction; the
# test over M is also the conservative one, since every phi that a colouring
# of the points supplies restricts to M, so blocking over M implies blocking
# for any larger group the points may generate.

def lattice_basis(vecs: Sequence[Sequence[int]]) -> List[List[int]]:
    """A Z-basis, in echelon form, of the lattice the integer vectors span.

    Entry growth is the whole difficulty: the necklace's coordinates carry
    hundred-digit denominators before they are cleared, and naive elimination
    squares that at every step.  Two things hold it down.  When the pivot
    divides the incoming entry the basis is left alone and only the incoming
    vector shrinks, which is the common case; and each finished row is reduced
    modulo the pivots below it, so the basis stays near-canonical instead of
    accumulating cofactors.
    """
    d = len(vecs[0])
    basis: dict = {}
    for row in vecs:
        w = list(row)
        c = 0
        while c < d:
            if w[c] == 0:
                c += 1
                continue
            if c not in basis:
                basis[c] = [-x for x in w] if w[c] < 0 else w
                break
            b = basis[c]
            if w[c] % b[c] == 0:
                q = w[c] // b[c]
                w = [x - q * y for x, y in zip(w, b)]
                c += 1
                continue
            g, x, y = _ext_gcd(b[c], w[c])
            nb = [x * bb + y * ww for bb, ww in zip(b, w)]
            w = [(b[c] // g) * ww - (w[c] // g) * bb for bb, ww in zip(b, w)]
            basis[c] = nb
            c += 1
    piv = sorted(basis)
    out = [basis[c] for c in piv]
    for i in range(len(out) - 1, -1, -1):
        for j in range(i + 1, len(out)):
            c = piv[j]
            if out[i][c]:
                q = out[i][c] // out[j][c]
                if q:
                    out[i] = [x - q * y for x, y in zip(out[i], out[j])]
    return out


def _ext_gcd(a: int, b: int) -> Tuple[int, int, int]:
    old_r, r = a, b
    old_s, s = 1, 0
    old_t, t = 0, 1
    while r:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
        old_t, t = t, old_t - q * t
    if old_r < 0:
        old_r, old_s, old_t = -old_r, -old_s, -old_t
    return old_r, old_s, old_t


def on_lattice(vecs: Sequence[Sequence[int]]) -> List[Tuple[int, ...]]:
    """The same vectors, in coordinates where their lattice IS Z^r.

    Use this before `has_homomorphism` whenever the answer is to be read as a
    statement about coset colourings.  Without it the search runs over the
    ambient Z^d and can report blocking the module does not have.
    """
    d = len(vecs[0])
    B = lattice_basis(vecs)
    piv = []
    for b in B:
        piv.append(next(i for i, x in enumerate(b) if x))
    out = set()
    for v in vecs:
        w, co = list(v), []
        for b, c in zip(B, piv):
            q, rem = divmod(w[c], b[c])
            if rem:
                raise ValueError("vector outside the computed lattice")
            co.append(q)
            if q:
                w = [x - q * y for x, y in zip(w, b)]
        if any(w):
            raise ValueError("Hermite reduction left a residue")
        out.add(tuple(co))
    return sorted(out)


def _rank_mod(vecs: Sequence[Sequence[int]], p: int) -> int:
    A = [[x % p for x in v] for v in vecs]
    d, row, rk = len(A[0]), 0, 0
    for c in range(d):
        piv = next((i for i in range(row, len(A)) if A[i][c]), None)
        if piv is None:
            continue
        A[row], A[piv] = A[piv], A[row]
        inv = pow(A[row][c], -1, p)
        A[row] = [(x * inv) % p for x in A[row]]
        for i in range(len(A)):
            if i != row and A[i][c]:
                f = A[i][c]
                A[i] = [(x - f * y) % p for x, y in zip(A[i], A[row])]
        row += 1
        rk += 1
    return rk


def _rank_q(vecs: Sequence[Sequence[int]]) -> int:
    A = [[Fraction(x) for x in v] for v in vecs]
    d, row, rk = len(A[0]), 0, 0
    for c in range(d):
        piv = next((i for i in range(row, len(A)) if A[i][c]), None)
        if piv is None:
            continue
        A[row], A[piv] = A[piv], A[row]
        f = A[row][c]
        A[row] = [x / f for x in A[row]]
        for i in range(row + 1, len(A)):
            if A[i][c]:
                g = A[i][c]
                A[i] = [x - g * y for x, y in zip(A[i], A[row])]
        row += 1
        rk += 1
    return rk


def saturated_at(vecs: Sequence[Sequence[int]], n: int) -> bool:
    """Do the Z^d test and the module test agree at this modulus?

    They agree exactly when no invariant factor of M shares a prime with n,
    which is exactly when the rank of the direction matrix survives reduction
    mod each prime dividing n.  Two eliminations settle it, and it is worth
    asking first: when the answer is yes the cheap test is correct, and the
    Hermite reduction -- which has to work on eighty-digit entries for
    anything built over a tower -- can be skipped.
    """
    rq = _rank_q(vecs)
    m, ps = n, []
    f = 2
    while f * f <= m:
        if m % f == 0:
            ps.append(f)
            while m % f == 0:
                m //= f
        f += 1
    if m > 1:
        ps.append(m)
    return all(_rank_mod(vecs, p) == rq for p in ps)


def _mod_reduce(vecs: Sequence[Sequence[int]], n: int):
    """phi(v) depends only on v mod n, so fold first -- and a residue of zero
    is a genuine obstruction, meaning the set contains n times one of its own
    members, which every phi kills."""
    out = set()
    for v in vecs:
        w = tuple(x % n for x in v)
        if not any(w):
            return None
        out.add(w)
    return sorted(out)


def blocks_at(vecs: Sequence[Sequence[int]], n: int) -> bool:
    """Is there no coset colouring mod n? Asked of the right group.

    The module test is the honest one, but the Hermite reduction it needs is
    expensive on the hundred-digit coordinates a tower produces.  So ask
    `saturated_at` first: when it holds the ambient test is already correct.
    """
    use = vecs if saturated_at(vecs, n) else on_lattice(vecs)
    small = _mod_reduce(use, n)
    if small is None:
        return True
    return has_homomorphism(small, n)[0] is None



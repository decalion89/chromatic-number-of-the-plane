def agreeing_pairs(cols, colours=5):
    """Indices that take the same colour in EVERY sampled colouring.

    The direct test compares every pair against every sample, which is
    O(samples * n^2): ten billion element comparisons at 27000 vertices, about
    three hours for one graph.  But agreeing in every sample is exactly having
    the same colour signature across the samples, so the pairs never have to
    be compared at all.  Read each vertex's signature as a number in base
    `colours`, sort, and the candidates are the pairs inside a bucket.

    With fourteen samples there are 5^14 signatures -- six billion -- so on any
    graph that fits in memory almost every bucket is a singleton and the few
    collisions are the whole candidate set.  O(n log n), and the size of the
    graph stops mattering.

    `cols` is a sequence of `samples` sequences of length n, each a proper
    colouring.  Returns sorted (i, j) with i < j.
    """
    if not cols:
        return []
    n = len(cols[0])
    key = [0] * n
    for row in cols:
        for v in range(n):
            key[v] = key[v] * colours + row[v]
    order = sorted(range(n), key=lambda v: key[v])
    out, start = [], 0
    while start < n:
        stop = start + 1
        while stop < n and key[order[stop]] == key[order[start]]:
            stop += 1
        if stop - start > 1:
            grp = sorted(order[start:stop])
            for a in range(len(grp)):
                for b in range(a + 1, len(grp)):
                    out.append((grp[a], grp[b]))
        start = stop
    return sorted(out)

def doubly_usable_ring(d2, radicands=(3, 5, 7, 11)):
    """Can this ring carry both halves of the step, rotation and spindle?

    A ring of squared radius D about the centre of a symmetric core is used
    twice, and each use costs a radical.

    First, rho: the rotation that makes the ring bite, carrying each of its
    points to distance exactly 1 from itself.  From |r e^{it} - r|^2 = 1 that
    is cos t = 1 - 1/(2D), sin t = sqrt(4D-1)/(2D), so the field must contain
    sqrt(4D-1).  That is `closable_distance(D)`.

    Second, the spindle: the pair the construction aims at is the ANTIPODAL
    pair on that ring, which sits at squared distance 4D.  Forcing it is only
    worth anything if it can then be spindled, and that rotation needs
    sqrt(4(4D)-1) = sqrt(16D-1).  That is `closable_distance(4*D)`.

    Requiring both at once is a savage filter, and the reason to trust it is
    that it retrodicts de Grey's choice uniquely.  Sa has five rational
    closable rings -- 1, 1/3, 5/9, 4, 3 -- and apart from the degenerate D = 1,
    which is the 60-degree rotation that fixes Sa, exactly one passes both:
    D = 4.  That is the ring he used, and the pair he forces, (2,0) and
    (-2,0), is its antipodal pair.
    """
    if d2 == 1:                       # the 60-degree turn: it fixes the core
        return False
    return (closable_distance(d2, radicands)
            and closable_distance(4 * d2, radicands))

def decay_rates(curve, tail_from=5):
    """Head rate, tail rate and floor of a survivor curve.

    `curve` is a list of (samples, survivors) marks, which need NOT be evenly
    spaced -- in practice they are taken at 1, 2, 3, 5, 10, 20, 40.  That is
    the whole reason this function exists.  Averaging a ratio measured over
    two samples together with ratios measured over one understates the rate,
    which is exactly the mistake it was written to stop: it once turned 0.238
    and 0.242 into 0.228 and 0.229 and made a stack look flatter than it was.

    The head rate uses consecutive marks only.  The tail rate is taken as a
    geometric mean per sample from `tail_from` to the last positive mark, and
    is None when the curve has no positive tail.  The floor is the last
    survivor count: a graph that forces something cannot reach zero, because
    the forced pair agrees in every colouring there is.
    """
    marks = [(int(s), int(c)) for s, c in curve]
    head = [b / a for (s1, a), (s2, b) in zip(marks, marks[1:])
            if s2 == s1 + 1 and a > 0]
    head_rate = sum(head) / len(head) if head else None
    lo = [m for m in marks if m[0] >= tail_from and m[1] > 0]
    tail_rate = None
    if len(lo) >= 2 and lo[0][1] > 0 and lo[-1][0] > lo[0][0]:
        tail_rate = (lo[-1][1] / lo[0][1]) ** (1.0 / (lo[-1][0] - lo[0][0]))
    return head_rate, tail_rate, marks[-1][1]


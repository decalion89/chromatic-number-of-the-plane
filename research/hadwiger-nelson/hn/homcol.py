def _coords(e) -> Tuple[Fraction, ...]:
    """Full rational coordinates, including a real extension's radical part.

    `.c` on a RealExtElement returns only its base component, so using it here
    silently truncated the edge vectors of anything living over sqrt(v) and
    reported a homomorphism search on the wrong module. Both halves are needed.
    """
    a = getattr(e, "a", None)
    b = getattr(e, "b", None)
    if a is not None and b is not None:
        return tuple(a.c) + tuple(b.c)
    return tuple(e.c)


def edge_vectors(graph) -> List[Tuple[int, ...]]:
    """Distinct edge vectors as integer tuples, over a common denominator."""
    out = set()
    for a, b in graph.edges():
        d = (graph.vertices[b].x - graph.vertices[a].x,
             graph.vertices[b].y - graph.vertices[a].y)
        out.add(_coords(d[0]) + _coords(d[1]))
    den = 1
    for v in out:
        for q in v:
            den = den * Fraction(q).denominator // gcd(den,
                                                       Fraction(q).denominator)
    ints = {tuple(int(Fraction(q) * den) for q in v) for v in out}
    # Divide out the common content. Clearing denominators multiplies every
    # vector by the same integer, and if that integer shares a factor with n
    # the whole set looks divisible by n -- a scaling artefact, not an
    # obstruction. Reported as one until this line existed.
    content = 0
    for v in ints:
        for x in v:
            content = gcd(content, abs(x))
    if content > 1:
        ints = {tuple(x // content for x in v) for v in ints}
    return sorted(ints)


def has_homomorphism(vecs: Sequence[Sequence[int]], n: int
                     ) -> Tuple[Optional[Tuple[int, ...]], str]:
    """A phi in (Z/n)^dim nonzero on every vector, by SAT. Dimension-free."""
    from pysat.formula import IDPool
    from pysat.solvers import Solver

    vecs = [tuple(v) for v in vecs]
    dim = len(vecs[0])
    pool = IDPool()
    cls = []

    def phi(i, val):
        return pool.id(("phi", i, val))

    for i in range(dim):
        cls.append([phi(i, v) for v in range(n)])
        for a in range(n):
            for b in range(a + 1, n):
                cls.append([-phi(i, a), -phi(i, b)])

    for t, d in enumerate(vecs):
        idx = [i for i in range(dim) if d[i] % n]
        if not idx:
            return None, f"an edge vector is divisible by {n}"

        def s(j, val):
            return pool.id(("s", t, j, val))

        for val in range(n):
            cls.append([-phi(idx[0], val), s(0, (val * d[idx[0]]) % n)])
        for j in range(1, len(idx)):
            for prev in range(n):
                for val in range(n):
                    cls.append([-s(j - 1, prev), -phi(idx[j], val),
                                s(j, (prev + val * d[idx[j]]) % n)])
        cls.append([-s(len(idx) - 1, 0)])

    with Solver(name="cd19", bootstrap_with=cls) as sv:
        if not sv.solve():
            return None, "no homomorphism in this embedding"
        m = set(sv.get_model())
        return tuple(next(v for v in range(n) if phi(i, v) in m)
                     for i in range(dim)), "found"


def screen(graph, n: int = 5) -> dict:
    """Can this graph ever be (n+1)-chromatic? A homomorphism says no."""
    vecs = edge_vectors(graph)
    phi, why = has_homomorphism(vecs, n)
    return {
        "edge_vectors": len(vecs),
        "dimension": len(vecs[0]),
        "homomorphism": phi,
        "verdict": (f"{n}-colourable by cosets, so never {n+1}-chromatic"
                    if phi else f"no coset {n}-colouring in this embedding"),
    }


# -- where a coset colouring can and cannot be blocked --------------------
#
# phi must avoid every edge vector, so writing D for their images in M/5M, a
# phi exists unless the hyperplanes d-perp for d in D cover the whole dual.
# Two facts bound where that can happen, and the first is a theorem.
#
# RANK 2 NEVER BLOCKS. If the edge vectors span only rank 2 mod 5 then M is a
# plane lattice, every unit vector has the same norm N, and the value of the
# quadratic form on a projective point is well defined up to squares -- so all
# of them land in one square class, which is three of the six points of the
# projective line. Three hyperplanes cover 13 of the 25 points of (Z/5)^2, so
# a phi always survives. Measured on the Eisenstein lattice at norms 1, 3, 7,
# 13, 21, 49 and 91: every one gives exactly THREE classes, and which three is
# decided by whether N is a square mod 5 -- {(0,1),(1,0),(1,1)} when it is,
# {(1,2),(1,3),(1,4)} when it is not. Even 24 unit vectors, at norm 91, give
# three.
#
# RANK 3 FAILS TOO, for the same kind of reason: the unit vectors lie on a
# conic of PG(2,5), and a conic has exterior lines -- 10 of them -- so a phi
# again survives. From rank 4 upward Chevalley-Warning makes every hyperplane
# carry vectors of the right norm, so blocking becomes possible in principle.
#
# COUNTING IS NOT ENOUGH. A random phi survives m hyperplanes with probability
# (4/5)^m, so coverage needs roughly m > 7.2 r. That predicts the three-hexagon
# gadget (r = 4, m = 18, threshold 29) correctly and de Grey's G (r = 16,
# m = 133, threshold 115) wrongly -- G clears the count and still admits a phi.
# The unit vectors are confined to the quadric Q = N, and being few points of
# it is what matters, not being many points overall. Every root-of-unity step
# set up to n = 105 admits one: Z[zeta_n] has n distinct directions against
# rank phi(n), a ratio that never exceeds about 3.5.

RANK_TWO_NEVER_BLOCKS = (
    "a plane lattice's unit vectors all share one norm, so their projective "
    "classes mod 5 lie in one square class: three of six, never a blocking set"
)


# -- and the cheapest blocking set is unreachable -------------------------
#
# Blocking a coset colouring means the hyperplanes d-perp cover the dual, which
# asks the directions D to meet every hyperplane -- a blocking set. In
# PG(r-1,5) the smallest one is a projective LINE, six points. So the cheapest
# possible route is six unit vectors whose directions are the six points of a
# line. It does not exist.
#
# THEOREM. No projective line over F_5 has all six of its points carrying a
# quadratic form value in one square class. Hence the directions of unit
# vectors -- which all satisfy Q(d) = N for one N -- never contain a complete
# line.
#
# Checked exhaustively over every binary form (a, b, c) over F_5 and every
# target N: the maximum is FIVE of the six points, reached only when the form
# degenerates to rank one. The cases are easy to see by hand too. Anisotropic
# gives three of six, the two square classes splitting the line evenly;
# hyperbolic gives two, because two of the points are isotropic and carry
# Q = 0; rank one gives five, the sixth point being the radical.
#
# So the minimum blocking set is out of reach, and blocking would need a
# larger one. Measured across pairs of imaginary quadratic fields -- the only
# source here of infinitely many unit vectors at fixed rank, since the
# modulus-one elements of Q(sqrt-d1, sqrt-d2) are exactly the products of one
# from each factor -- the direction sets reach 25 at rank 4 and contain ZERO
# complete lines, on every pair tried.
#
# One trap, and it produced a false positive before it was found. Some of
# those generators have denominators divisible by 5, for instance
# (1 + 3 sqrt-11)/10. The module then stops being 5-integral, clearing
# denominators makes EVERY vector divisible by 5, and the search dutifully
# reports "no homomorphism" -- for reasons of arithmetic bookkeeping and
# nothing else. Generators must be filtered to denominators coprime to 5.

UNIT_DIRECTIONS_MISS_A_LINE = (
    "unit vectors all have one norm N, and no projective line over F_5 has "
    "all six points with Q in one square class -- at most five, and only for "
    "a degenerate form -- so they never contain the minimum blocking set"
)


# -- and where a blocking set finally exists ------------------------------
#
# The multiquadratic families fail for a reason that is quantitative and
# final. The projective direction count of the modulus-one group mod 5 is a
# product of small factors -- 3 where 5 is inert in a quadratic factor, 2
# where it splits -- so Q(sqrt-d1,...,sqrt-dt) of degree 2t gives at most 3^t
# directions against PG(2t-1,5)'s (5^2t - 1)/4 points. Measured: 6 at (7,11),
# 9 at (7,23), and 27 at (7,23,43) against 97656. The ratio (3/25)^t
# collapses, and more generators do not help, because the group is finite and
# already exhausted.
#
# The cause is the splitting. In a multiquadratic field the Galois group is
# (Z/2)^t and the decomposition group at 5 is cyclic, so the residue degree is
# at most 2 and O/5 breaks into many tiny fields. A LARGE norm-one group needs
# the decomposition group to be everything -- a CYCLIC Galois group with 5
# inert, which means Q(zeta_n) with 5 a primitive root mod n.
#
# n = 7 qualifies: 5 has order 6 in (Z/7)^*. Then O/5 = F_5^6 and the norm-one
# subgroup has (5^6 - 1)/(5^3 - 1) = 126 elements. Modulus-one elements come
# free from Hilbert 90 -- u = alpha/conj(alpha) has modulus one for every
# alpha, with denominator a norm, which only has to stay coprime to 5.
#
# RESULT. Sixty-three of those directions, at full rank 6, admit NO
# homomorphism to Z/5. Verified by brute force over all 5^6 = 15625 maps, not
# on the solver's word: zero survive. It is the first step set in this package
# with no coset 5-colouring at all.
#
# What that is and is not. It removes the structural colouring, which every
# other graph here had; it does not make any particular graph 6-chromatic,
# since an unstructured 5-colouring may still exist and only a solver can say.
# It is a necessary condition, met for the first time.


def _coord(spec: Dict[int, Fr], field: Field):
    out = field.zero()
    for radicand, coeff in spec.items():
        term = field.rational(coeff) if radicand == 1 else field.sqrt(radicand) * field.rational(coeff)
        out = out + term
    return out


def build_S(field: Field = DEGREY_FIELD) -> List[Point]:
    return [Point(_coord(x, field), _coord(y, field)) for x, y in S_POINTS]


def build_Sa(field: Field = DEGREY_FIELD) -> List[Point]:
    """Every image of S under the 60-degree rotation and reflection in y."""
    rot60 = _rot60(field)
    seen, out = set(), []
    for p in build_S(field):
        for base in (p, Point(p.x, -p.y)):
            q = base
            for _ in range(6):
                if q not in seen:
                    seen.add(q)
                    out.append(q)
                q = rot60(q)
    return out


def _rot_2asin_quarter(field: Field) -> Rotation:
    """2*arcsin(1/4): cos 7/8, sin sqrt(15)/8."""
    return Rotation(field.rational(Fr(7, 8)), field.sqrt(15) * field.rational(Fr(1, 8)))


def _rot_half_pi_pm(field: Field, sign: int) -> Rotation:
    """pi/2 +- arcsin(1/8): cos -+1/8, sin 3*sqrt(7)/8."""
    return Rotation(field.rational(Fr(-sign, 8)), field.sqrt(7) * field.rational(Fr(3, 8)))


def build_Sb(field: Field = DEGREY_FIELD) -> List[Point]:
    rot = _rot_2asin_quarter(field)
    return [rot(p) for p in build_Sa(field)]


def build_Y(field: Field = DEGREY_FIELD) -> List[Point]:
    """Sa u Sb, less the two vertices (1/3, 0) and (-1/3, 0)."""
    drop = {
        Point(field.rational(Fr(1, 3)), field.zero()),
        Point(field.rational(Fr(-1, 3)), field.zero()),
    }
    seen, out = set(), []
    for p in build_Sa(field) + build_Sb(field):
        if p in drop or p in seen:
            continue
        seen.add(p)
        out.append(p)
    return out


def build_G(field: Field = DEGREY_FIELD, as_graph: bool = True):
    """Ya u Yb: the 1581-vertex graph."""
    pivot = Point(field.rational(-2), field.zero())
    Y = build_Y(field)
    pts, seen = [], set()
    for sign in (+1, -1):
        turn = _rot_half_pi_pm(field, sign).about(pivot)
        for p in Y:
            q = turn(p)
            if q not in seen:
                seen.add(q)
                pts.append(q)
    return build_graph(pts) if as_graph else pts

"""de Grey's 1581-vertex 5-chromatic graph, rebuilt from the published recipe.

Source: Aubrey D.N.J. de Grey, "The chromatic number of the plane is at least 5",
arXiv:1804.02385 / Geombinatorics 28 (2018).  The construction there is:

    S    39 explicit points (section 5.1 of the paper, transcribed below)
    Sa   every image of S under the 12-element group generated by the
         60-degree rotation and reflection in the x-axis
    Sb   Sa rotated anticlockwise about the origin by 2*arcsin(1/4)
    Y    Sa u Sb, with the two vertices (1/3, 0) and (-1/3, 0) deleted
    Ya   Y rotated anticlockwise about (-2, 0) by pi/2 + arcsin(1/8)
    Yb   Y rotated anticlockwise about (-2, 0) by pi/2 - arcsin(1/8)
    G    Ya u Yb        -- 1581 vertices, and not 4-colourable

S itself lies in Q(sqrt3, sqrt11).  The rotation by 2*arcsin(1/4) has sine
sqrt(15)/8 and the two about (-2,0) have sine 3*sqrt(7)/8, so G needs
Q(sqrt3, sqrt5, sqrt7, sqrt11) -- which is why searching inside Q(sqrt3,
sqrt11) could never have found it.

Nothing here is taken on faith: `hn.certify` re-derives every edge from these
coordinates in O(n^2) and drat-trim checks the proof that no 4-colouring
exists.  Transcription errors would show up as a wrong vertex count or a
graph that turns out to be 4-colourable.
"""


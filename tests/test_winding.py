"""Theorem W (notes/winding_lemma.md): an abelian Cayley graph maps to the odd cycle C_{2k+1} if and only if some
character sends every generator into [k/(2k+1), (k+1)/(2k+1)]; for k = 1 this characterises 3-colourability.

Checked here: the theorem on random Cayley graphs of Z/m x Z/n (k = 1 and k = 2), the corollary for groups of
exponent 2 and 4, the distance-graph form against Zhu's list, and the exact certificates that no character of the
group generated by the unit vectors maps them into [1/3, 2/3] over Q(sqrt d) for d = 11, 83, 143, 203 (and, marked
slow, 107 and 167)."""

def _first_leaf(t):
    stack = [t]
    while stack:
        x = stack.pop()
        if "leaf" in x:
            return x
        stack.extend(x["kids"].values())


def _mutations(C):
    m = copy.deepcopy(C); _first_leaf(m["tree"])["leaf"][0] = 0.5; yield "float in a leaf", m
    m = copy.deepcopy(C); m["D"] = 30.0; yield "float denominator", m
    m = copy.deepcopy(C); m["units"][0][0] += 1; yield "not a unit vector", m
    m = copy.deepcopy(C); m["relations"][0][0] += 1; yield "not a relation", m
    m = copy.deepcopy(C); m["tree"]["kids"].pop(next(iter(m["tree"]["kids"]))); yield "missing branch value", m
    m = copy.deepcopy(C); leaf = _first_leaf(m["tree"]); leaf["leaf"] = ["0"] * len(leaf["leaf"]); yield "zero leaf", m


def test_checker_rejects_bad_certificates(tmp_path):
    """check_w raises CertificateError (not AssertionError, so python -O checks the same) on each mutation."""
    with gzip.open(os.path.join(WDIR, "cert_11_30.json.gz"), "rt") as fh:
        C = json.load(fh)
    good = tmp_path / "good.json"; good.write_text(json.dumps(C))
    assert check(str(good)).startswith("VERIFIED: d=11 ")
    for name, m in _mutations(C):
        bad = tmp_path / "bad.json"; bad.write_text(json.dumps(m))
        with pytest.raises(CertificateError):
            check(str(bad))

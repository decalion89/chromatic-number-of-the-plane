def _hom_to_cycle(m, n, S, p):
    """does Cay(Z/m x Z/n, S) map to C_p (p odd >= 3)?  SAT, one-hot colours."""
    N = m * n
    v = lambda x, c: p * x + c + 1
    s = Solver(name="cadical195")
    for x in range(N):
        s.add_clause([v(x, c) for c in range(p)])
    for a in range(m):
        for b in range(n):
            x = a * n + b
            for (da, db) in S:
                y = ((a + da) % m) * n + (b + db) % n
                if x == y:
                    return False
                for c in range(p):
                    for c2 in range(p):
                        if (c2 - c) % p not in (1, p - 1):
                            s.add_clause([-v(x, c), -v(y, c2)])
    return s.solve()


def _character_exists(m, n, S, k):
    """is there a character (j/m, l/n) with xi(s) in [k/(2k+1), (k+1)/(2k+1)] for all s in S?"""
    p = 2 * k + 1
    for j in range(m):
        for l in range(n):
            if all(Fr(k, p) <= (Fr(j * da, m) + Fr(l * db, n)) % 1 <= Fr(k + 1, p) for (da, db) in S):
                return True
    return False


def _random_connection_sets(seed, count):
    rnd = random.Random(seed)
    out = []
    while len(out) < count:
        m = rnd.randint(3, 11); n = rnd.choice([1, 1, 2, 3, 4, 5])
        S = set()
        for _ in range(rnd.randint(1, 3)):
            a, b = rnd.randrange(m), rnd.randrange(n)
            if (a, b) != (0, 0):
                S.add((a, b)); S.add(((-a) % m, (-b) % n))
        if S:
            out.append((m, n, sorted(S)))
    return out


@pytest.mark.parametrize("k", [1, 2])
def test_theorem_w_on_random_cayley_graphs(k):
    p = 2 * k + 1
    agree = {True: 0, False: 0}
    for m, n, S in _random_connection_sets(100 + k, 250):
        a = _hom_to_cycle(m, n, S, p)
        assert a == _character_exists(m, n, S, k), (m, n, S, p)
        agree[a] += 1
    assert agree[True] > 20 and agree[False] > 20


def test_exponent_two_and_four_are_never_three_chromatic():
    """characters of a group of exponent 2 or 4 take values in (1/4)Z/Z, and only 1/2 lies in [1/3, 2/3]."""
    rnd = random.Random(7)
    for (m, n) in [(2, 2), (4, 2), (4, 4)]:
        for _ in range(60):
            S = set()
            for _ in range(rnd.randint(1, 3)):
                a, b = rnd.randrange(m), rnd.randrange(n)
                if (a, b) != (0, 0):
                    S.add((a, b)); S.add(((-a) % m, (-b) % n))
            if not S:
                continue
            S = sorted(S)
            if _hom_to_cycle(m, n, S, 3):
                # 3-colourable, hence bipartite: every generator has a character value 1/2
                assert _character_exists(m, n, S, 1)
                two = Solver(name="cadical195")
                N = m * n
                for a in range(m):
                    for b in range(n):
                        x = a * n + b
                        for (da, db) in S:
                            y = ((a + da) % m) * n + (b + db) % n
                            two.add_clause([x + 1, y + 1]); two.add_clause([-(x + 1), -(y + 1)])
                assert two.solve(), (m, n, S)


def _kappa_third(D):
    cands = {Fr(3 * j + r, 3 * d) for d in D for j in range(d) for r in (1, 2)}
    return any(all(Fr(1, 3) <= (a * d) % 1 <= Fr(2, 3) for d in D) for a in cands)


def _segment_3col(D, N):
    s = Solver(name="cadical195"); v = lambda x, c: 3 * x + c + 1
    for x in range(N):
        s.add_clause([v(x, c) for c in range(3)])
        for d in D:
            if x + d < N:
                for c in range(3):
                    s.add_clause([-v(x, c), -v(x + d, c)])
    return s.solve()


def test_distance_graphs_against_zhu():
    four = []
    for D in itertools.combinations(range(1, 13), 3):
        if math.gcd(math.gcd(D[0], D[1]), D[2]) != 1:
            continue
        k = _kappa_third(D)
        assert k == _segment_3col(D, 12 * max(D) + 60), D
        if not k:
            four.append(D)
    zhu = [D for D in itertools.combinations(range(1, 13), 3) if math.gcd(math.gcd(D[0], D[1]), D[2]) == 1
           and ((D[0], D[1]) == (1, 2) and D[2] % 3 == 0 or D[0] + D[1] == D[2] and (D[0] - D[1]) % 3)]
    assert four == zhu and len(four) > 10


